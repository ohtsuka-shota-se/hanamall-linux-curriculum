set -e
echo "================================================"
echo " Week03 障害環境セットアップ"
echo " 「CPU急騰 + 新メンバーのアカウント未設定」"
echo "================================================"

# 【状況1】バックグラウンドで CPU を食い続けるプロセスを起動
echo ""
echo "【1】CPU を消費し続けるプロセスを起動します（障害再現）..."

# 複数の重いプロセスをバックグラウンドで起動
for i in 1 2 3; do
  yes > /dev/null &
done

# PID を記録しておく
jobs -p > /tmp/week03_pids.txt
echo "✅ 高負荷プロセスを起動しました（PID: $(cat /tmp/week03_pids.txt | tr '\n' ' ')）"
echo "   top コマンドで確認すると yes が上位に来るはずです"

# 【状況2】dev_team グループと suzuki ユーザーを未設定状態にする（既存なら削除）
echo ""
echo "【2】鈴木さんのアカウントを「未設定の状態」にします..."
sudo userdel -r suzuki 2>/dev/null && echo "   既存の suzuki を削除しました" || true
sudo groupdel dev_team 2>/dev/null && echo "   既存の dev_team グループを削除しました" || true
echo "✅ アカウント未設定状態にしました"

# 状態確認
echo ""
echo "================================================"
echo " セットアップ完了！以下の状態になっています："
echo ""
echo "  ❌ CPU使用率  : 高負荷プロセスが動いています"
echo "  ❌ suzuki     : アカウント未作成"
echo "  ❌ dev_team   : グループ未作成"
echo ""
echo " 佐藤さんからSlackが来ています："
echo " 「監視アラートで CPU 90%超が来ました！」"
echo " 「来週から鈴木さんが参加します。アカウント設定お願いします」"
echo ""
echo " → 次は 03_user_process.sh を実行して対応してください"
echo "================================================"
